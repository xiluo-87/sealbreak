/**
 * The sack: 24 letters (design 5.4), plus Gran's Letter. Each letter's text is
 * written out in full. `hand` records who really wrote it; it is never shown
 * in the interface.
 */
import type { Tone } from './party';

export type Hand = 'real' | 'forged';
export type LetterStyle = 'soldier' | 'elegant' | 'official' | 'scrawl' | 'plain' | 'neat' | 'careful' | 'formal' | 'child' | 'pencil';

export interface Reward {
  coin?: number;
  items?: Record<string, number>;
  accessory?: string;
  flags?: string[];
  /** Shown in the delivery message. */
  note: string;
}

export interface LetterDef {
  id: string;
  title: string;
  from: string;
  to: string;
  region: 'thistle' | 'fen' | 'copperhill' | 'salt' | 'kingsend' | 'detour';
  hand: Hand;
  tone: Tone;
  carry: string;
  burst: string;
  /** Overrides for letters whose skills differ from their tone's usual effect. */
  special?: string;
  reward: Reward;
  style: LetterStyle;
  /** Postmark date, as written on the envelope. */
  postmark: string;
  body: string[];
  signature: string;
}

